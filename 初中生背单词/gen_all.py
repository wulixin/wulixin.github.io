#!/usr/bin/env python3
"""批量生成名词、动词、时态、形容词、短语、CET4/6 题库 — 每类 400-600 题"""
import json, random, os
random.seed(42)
OUT = os.path.join(os.path.dirname(__file__), "data")
os.makedirs(OUT, exist_ok=True)
_i = [1000]
def nid(): _i[0] += 1; return _i[0]
def mc(q,h,o,a,x,e,m,c,d):
    return {"id":nid(),"cat":c,"diff":d,"type":"mc","q":q,"hint":h,"options":o,"answer":a,"explain":x,"examples":e,"mnemonic":m}
def fl(q,h,a,x,e,m,c,d):
    return {"id":nid(),"cat":c,"diff":d,"type":"fill","q":q,"hint":h,"answer":a,"explain":x,"examples":e,"mnemonic":m}
def save(n,d): 
    with open(os.path.join(OUT,n),'w',encoding='utf-8') as f: json.dump(d,f,ensure_ascii=False,indent=2)
    print(f"  ✅ {n}: {len(d)} 题")

# ========== NOUNS ==========
def gen_nouns():
    Q=[]
    # 不可数名词量词
    unc = {"advice":"建议","information":"信息","furniture":"家具","news":"消息","equipment":"设备","luggage":"行李","progress":"进步","knowledge":"知识","evidence":"证据","music":"音乐","homework":"作业","research":"研究","traffic":"交通","weather":"天气","money":"钱","time":"时间"}
    for n,zh in unc.items():
        for qty in ["a piece of","a bit of","an item of","a lot of"]:
            opts=["a","an","—","the"]; random.shuffle(opts)
            Q.append(mc(f"She gave me ___ useful {n}.",f'{zh}不可数，用piece等量词',opts,opts.index("—") if qty.startswith("a") else 0,
                f'"{n}"是不可数名词，不用a/an。量词用piece of。','','','noun','easy'))
    # 不规则复数
    irr = [("child","children","孩子们"),("mouse","mice","老鼠"),("foot","feet","脚"),("tooth","teeth","牙齿"),
           ("person","people","人"),("man","men","男人"),("woman","women","女人"),("sheep","sheep","羊"),
           ("fish","fish","鱼"),("deer","deer","鹿"),("ox","oxen","牛"),("goose","geese","鹅")]
    for s,p,zh in irr:
        opts=random.sample([x[1] for x in irr if x[1]!=p],3)+[p]; random.shuffle(opts)
        Q.append(mc(f"There are three ___ in the field.",f'{zh}的复数形式',opts,opts.index(p),
            f'{s}的复数是不规则形式：{p}。',[f'Three <strong>{p}</strong> are in the field.'],f'{s}→{p}','noun','easy'))
    # 集合名词
    coll_n = [("family","家庭"),("team","团队"),("audience","观众"),("committee","委员会"),("class","班级"),("government","政府"),("staff","员工"),("crew","机组")]
    for n,zh in coll_n:
        for ctx,vb in [("整体","is"),("个体成员","are")]:
            opts=["is","are","was","were"]; random.shuffle(opts)
            a=opts.index(vb)
            Q.append(mc(f"The {n} ___ united in their decision.",f'{zh}作{ctx}时的谓语',opts,a,
                f'集合名词{n}作{ctx}时，谓语用{vb}。','','','noun','medium'))
    # 所有格
    for name in ["Tom","Mary","the teacher","my sister","James","the boss"]:
        Q.append(mc(f"___ car is red.",f'{name}的所有格',["Tom","Tom's","Toms","of Tom"],1,'','','','noun','easy'))
    # 复合名词
    comp = ["bedroom","basketball","notebook","airport","classroom","homework","newspaper","sunrise","password","raincoat","toothbrush","lighthouse","footprint","waterfall","skyscraper"]
    for w in comp:
        Q.append(fl(f"She bought a new ___. ({w}的意思)",f'复合名词: {w}',w,'','','','noun','easy'))
    # 名词辨析
    pairs = [
        (["problem","question","issue","matter"],0,"problem=需要解决的问题；question=提问的问题"),
        (["journey","trip","travel","tour"],1,"trip=短途旅行；journey=长途旅程；travel=泛指旅行；tour=观光"),
        (["work","job","career","occupation"],2,"career=长期职业；job=具体工作；work=不可数泛指工作"),
        (["error","mistake","fault","flaw"],1,"mistake=日常犯错；error=正式/技术性错误；fault=过失责任"),
        (["chance","opportunity","possibility","luck"],1,"opportunity=有利机会；chance=可能性或偶然机会"),
    ]
    for opts_list,ans,exp in pairs:
        random.shuffle(opts_list)
        Q.append(mc(f"It was a great ___ to study abroad.",'选择最合适的词',opts_list,opts_list.index(pairs[0][0][ans]),exp,'','','noun','medium'))
    # 数量表达
    for _ in range(20):
        Q.append(mc("___ number of students ___ increased.",
            'a number of vs the number of',
            ["A / have","A / has","The / have","The / has"],0,
            'a number of = 许多(复数谓语); the number of = ...的数量(单数谓语)','','','noun','medium'))
    # 抽象名词具体化
    abs_n = [("experience","经验/经历"),("beauty","美/美人"),("youth","青春/年轻人"),("authority","权威/当局"),("power","力量/大国")]
    for n,zh in abs_n:
        Q.append(mc(f"She had an unforgettable ___ in Paris.",f'{zh}',[n,"a "+n,"the "+n,n+"s"],1,
            f'{n}作可数时指具体{zh.split("/")[1] if "/" in zh else zh}。','','','noun','hard'))
    return Q

